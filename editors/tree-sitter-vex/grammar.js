// Structural VEX grammar. The language server, not this grammar, resolves names.
const commaSep1 = rule => seq(rule, repeat(seq(',', rule)));
const sep1 = (rule, separator) => seq(rule, repeat(seq(separator, rule)));
module.exports = grammar({
  name: 'vex',
  extras: $ => [/\s/, $.comment],
  word: $ => $.identifier,
  conflicts: $ => [[$.type_specifier, $.expression], [$.type_specifier, $.constructor_expression], [$.initializer, $.block]],
  rules: {
    source_file: $ => repeat($._statement),
    _statement: $ => choice($.function_definition, $.struct_definition, $.declaration, $.block,
      $.if_statement, $.loop_statement, $.return_statement, $.jump_statement,
      $.expression_statement, $.preprocessor, ';'),
    block: $ => seq('{', repeat($._statement), '}'),
    type_specifier: $ => choice($.primitive_type, alias($.identifier, $.type_identifier)),
    primitive_type: _ => choice('void', 'int', 'float', 'vector2', 'vector', 'vector4',
      'matrix2', 'matrix3', 'matrix', 'string', 'dict', 'bsdf', 'cvex', 'sop', 'surface',
      'displacement', 'light', 'shadow', 'fog', 'chop', 'cop2', 'image3d'),
    qualifier: _ => choice('const', 'export', 'uniform', 'varying'),
    array_suffix: $ => seq('[', optional($.expression), ']'),
    function_definition: $ => seq(optional('function'), repeat($.qualifier),
      field('type', $.type_specifier), repeat($.array_suffix), field('name', $.identifier),
      field('parameters', $.parameter_list), choice(field('body', $.block), ';')),
    parameter_list: $ => seq('(', optional(seq(sep1($.parameter, choice(';', ',')), optional(choice(';', ',')))), ')'),
    parameter: $ => prec.right(seq(repeat($.qualifier), $.type_specifier, repeat($.array_suffix),
      sep1(seq(field('name', $.identifier), repeat($.array_suffix), optional(seq('=', $.expression))), ','))),
    struct_definition: $ => prec.right(seq('struct', field('name', $.identifier), field('body', $.block), optional(';'))),
    declaration: $ => seq(repeat($.qualifier), $.type_specifier, repeat($.array_suffix),
      commaSep1($.declarator), ';'),
    declarator: $ => seq(field('name', $.identifier), repeat($.array_suffix), optional(seq('=', $.expression))),
    if_statement: $ => prec.right(seq('if', '(', $.expression, ')', $._statement, optional(seq('else', $._statement)))),
    loop_statement: $ => choice(
      seq(choice('for', 'foreach'), '(', optional($.loop_header), ')', $._statement),
      seq('while', '(', $.expression, ')', $._statement),
      seq('do', $._statement, 'while', '(', $.expression, ')', ';')),
    loop_header: $ => repeat1(choice($.parameter, $.expression, ';', ',', ':')),
    return_statement: $ => seq('return', optional($.expression), ';'),
    jump_statement: _ => seq(choice('break', 'continue'), ';'),
    expression_statement: $ => seq($.expression, ';'),
    expression: $ => choice($.identifier, $.attribute, $.number, $.string,
      $.parenthesized_expression, $.initializer, $.call_expression, $.constructor_expression, $.index_expression, $.concatenated_string,
      $.member_expression, $.unary_expression, $.binary_expression, $.assignment_expression,
      $.conditional_expression, $.cast_expression),
    parenthesized_expression: $ => seq('(', $.expression, ')'),
    initializer: $ => seq('{', optional(seq(commaSep1($.expression), optional(','))), '}'),
    call_expression: $ => prec(15, seq(field('function', $.expression), '(', optional(commaSep1($.expression)), ')')),
    constructor_expression: $ => seq($.primitive_type, repeat($.array_suffix), '(', optional(commaSep1($.expression)), ')'),
    index_expression: $ => prec(15, seq($.expression, '[', choice($.expression, $.slice), ']')),
    slice: $ => seq(optional($.expression), ':', optional($.expression), optional(seq(':', optional($.expression)))),
    member_expression: $ => prec(15, seq($.expression, choice('.', '->'), field('member', $.identifier))),
    concatenated_string: $ => prec.right(2, seq($.string, repeat1($.string))),
    cast_expression: $ => prec(13, seq('(', $.type_specifier, ')', $.expression)),
    unary_expression: $ => choice(
      prec(13, seq(choice('!', '~', '-', '+', '++', '--'), $.expression)),
      prec(14, seq($.expression, choice('++', '--')))),
    binary_expression: $ => choice(...[
      [12, ['*', '/', '%']], [11, ['+', '-']], [10, ['<<', '>>']],
      [9, ['<', '<=', '>', '>=']], [8, ['==', '!=']], [7, ['&']], [6, ['^']],
      [5, ['|']], [4, ['&&']], [3, ['||']]
    ].map(([p, ops]) => prec.left(p, seq($.expression, ops.length === 1 ? ops[0] : choice(...ops), $.expression)))),
    assignment_expression: $ => prec.right(1, seq($.expression,
      choice('=', '+=', '-=', '*=', '/=', '%=', '&=', '|=', '^=', '<<=', '>>='), $.expression)),
    conditional_expression: $ => prec.right(2, seq($.expression, '?', $.expression, ':', $.expression)),
    attribute: _ => token(/([ifvpu234sd](\[\])?)?@[A-Za-z_][A-Za-z_0-9]*/),
    identifier: _ => /[A-Za-z_][A-Za-z_0-9]*/,
    number: _ => token(choice(/0[xX][0-9a-fA-F]+/, /([0-9]+(\.[0-9]*)?|\.[0-9]+)([eE][+-]?[0-9]+)?[fF]?/)),
    string: _ => token(choice(/"([^"\\]|\\.)*"/, /'([^'\\]|\\.)*'/)),
    comment: _ => token(choice(/\/\/[^\n]*/, /\/\*[^*]*\*+([^/*][^*]*\*+)*\//)),
    preprocessor: _ => token(seq('#', /([^\n\\]|\\[^\n]|\\\n)*/)),
  }
});
