"""DEVELOPER tool: regenerate tools/opencl-lsp/ko_opencl_lsp/builtins.py.

Reads clang's OpenCL C builtin header (opencl-c.h, shipped with clangd/LLVM) and
writes a compact {name: {'sigs': [...], 'doc': '...'}} catalogue. Overloads that
differ only by vector width (float2/3/4/8/16) or address space are collapsed.

    python scripts/opencl_builtins.py "<path to>/lib/clang/<ver>/include/opencl-c.h"
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tools/opencl-lsp/ko_opencl_lsp/builtins.py'
ATTRIBUTES = re.compile(r'\b__(ovld|cnfn|purefn|conv|attribute__\s*\(\(.*?\)\))\b|__attribute__\s*\(\(.*?\)\)')
ADDRESS = re.compile(r'\b__(global|local|constant|private|generic)\s+')
WIDTH = re.compile(r'\b(half|float|double|u?char|u?short|u?int|u?long)(2|3|4|8|16)\b')
DECL = re.compile(r'^\s*([A-Za-z_][\w ]*?[\w*])\s*\b([A-Za-z_]\w*)\s*\(([^;{]*)\)\s*;', re.S)
SKIP = re.compile(r'^(__|convert_\w+_(rte|rtz|rtp|rtn)$|convert_\w+_sat_)')


def clean(text):
    return ' '.join(ATTRIBUTES.sub('', text).split())


def statements(source):
    """(declaration text, preceding /** doc */) for each top-level ';' declaration."""
    doc, buffer, block = '', '', None
    for line in source.splitlines():
        stripped = line.strip()
        if block is not None:
            block.append(stripped)
            if '*/' in stripped:
                text = ' '.join(block)
                text = re.sub(r'^/\*\*|\*/$', '', text).strip()
                doc = ' '.join(part.strip().lstrip('*').strip() for part in text.split(' * ')).strip()
                block = None
            continue
        if stripped.startswith('/**'):
            block = [stripped]
            if stripped.endswith('*/') and len(stripped) > 4:
                doc, block = stripped[3:-2].strip().lstrip('*').strip(), None
            continue
        if not stripped or stripped.startswith(('#', '//')):
            continue
        buffer += ' ' + stripped
        if stripped.endswith(';') or stripped.endswith('}'):
            yield buffer.strip(), doc
            buffer = ''
        if stripped.endswith('}'):
            doc = ''


def main(header):
    source = Path(header).read_text(encoding='utf-8')
    catalogue = {}
    for text, doc in statements(source):
        match = DECL.match(clean(text))
        if not match:
            continue
        returns, name, args = match[1].strip(), match[2], match[3].strip()
        if SKIP.match(name) or returns in ('typedef', 'return') or returns.startswith(('typedef', 'struct', 'enum')):
            continue
        signature = f'{returns} {name}({args})'
        generic = ADDRESS.sub('', signature)
        # vload3, convert_float4: the width is part of the name, so keep exact types.
        if not name[-1].isdigit():
            generic = WIDTH.sub(r'\1n', generic)
        entry = catalogue.setdefault(name, {'sigs': [], 'doc': ''})
        if generic not in entry['sigs']:
            entry['sigs'].append(generic)
        if doc and not entry['doc']:
            entry['doc'] = doc
    for entry in catalogue.values():
        # float first, then integers, then double/half; cap the list.
        def rank(sig):
            return (('double' in sig) + ('half' in sig), 'float' not in sig, len(sig))
        entry['sigs'] = sorted(entry['sigs'], key=rank)[:8]
    lines = [
        '"""OpenCL C built-in functions: GENERATED by scripts/opencl_builtins.py. Do not edit.',
        '',
        'Signatures and descriptions are derived from clang\'s opencl-c.h, part of the LLVM',
        'Project, under the Apache License v2.0 with LLVM Exceptions (https://llvm.org/LICENSE.txt).',
        '"n" in a type name stands for any of the widths 2, 3, 4, 8 and 16.',
        '"""',
        'BUILTINS = {',
    ]
    for name in sorted(catalogue):
        lines.append(f'    {name!r}: {catalogue[name]!r},')
    lines.append('}')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(catalogue)} functions -> {OUT}')


if __name__ == '__main__':
    main(sys.argv[1])
